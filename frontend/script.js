function renderLiveMap(slots) {
    const container = document.getElementById("liveMapContainer");
    if (!container || !Array.isArray(slots)) return;

    container.replaceChildren();

    const selectedZone = $("slotZoneFilter")?.value ?? "";
    document.querySelectorAll("[data-map-zone]").forEach((button) => {
        const active = button.dataset.mapZone === selectedZone;
        button.classList.toggle("active", active);
        button.setAttribute("aria-pressed", String(active));
    });

    const zoneMap = {};
    slots.forEach((slot) => {
        const z = String(slot.zone ?? "?").toUpperCase();
        if (selectedZone && z !== selectedZone) return;
        if (!zoneMap[z]) zoneMap[z] = [];
        zoneMap[z].push(slot);
    });

    const zones = Object.keys(zoneMap).sort();
    if (zones.length === 0) {
        const msg = document.createElement("p");
        msg.className = "data-message";
        msg.textContent = selectedZone
            ? `No parking spaces are configured in Zone ${selectedZone}.`
            : "No parking spaces are available to display.";
        container.append(msg);
        return;
    }

    zones.forEach((zone) => {
        const zoneSlots = zoneMap[zone];
        const activeSlots = zoneSlots.filter((s) => s.is_active !== false);
        const availCount = activeSlots.filter(
            (s) => String(s.current_status ?? "").toUpperCase() === "AVAILABLE"
        ).length;
        const occupiedCount = activeSlots.filter(
            (s) => String(s.current_status ?? "").toUpperCase() === "OCCUPIED"
        ).length;

        const panel = document.createElement("div");
        panel.className = `lm-zone-panel zone-${zone.toLowerCase()}`;
        panel.dataset.zone = zone;

        const zoneName = document.createElement("p");
        zoneName.className = "lm-zone-name";
        zoneName.textContent = `Zone ${zone}`;

        const zoneCount = document.createElement("p");
        zoneCount.className = "lm-zone-count";
        zoneCount.textContent = `${activeSlots.length} active · ${occupiedCount} occupied · ${availCount} available`;

        const grid = document.createElement("div");
        grid.className = "lm-slot-grid";

        zoneSlots.forEach((slot) => {
            const active = slot.is_active !== false;
            const status = String(slot.current_status ?? "AVAILABLE").toUpperCase();
            const isAvail = active && status === "AVAILABLE";
            const isOcc = active && status === "OCCUPIED";

            const btn = document.createElement("button");
            btn.type = "button";
            btn.className = `lm-slot-btn ${!active ? "slot-inactive" : isOcc ? "slot-occ" : "slot-avail"}`;
            btn.dataset.slotId = slot.slot_id ?? "";
            btn.dataset.zone = zone;
            btn.setAttribute("aria-pressed", String(String(slot.slot_id) === selectedSlotId));
            btn.setAttribute(
                "aria-label",
                `${slot.slot_id ?? "Parking space"}, Zone ${zone}, ${active ? status.toLowerCase() : "inactive"}, ${getSlotTypeLabel(slot.slot_type)}`
            );
            const vehicle = isOcc ? getVehicleIndicator(slot.vehicle_type) : null;
            btn.title = `${slot.slot_id} — ${active ? status : "INACTIVE"} (${slot.slot_type})${
                vehicle ? ` · ${vehicle.label}${slot.vehicle_no ? ` ${slot.vehicle_no}` : ""}` : ""
            }`;

            const idEl = document.createElement("span");
            idEl.className = "lm-slot-id";
            idEl.textContent = slot.slot_id ?? "?";

            const typeEl = document.createElement("span");
            typeEl.className = "lm-slot-type";
            typeEl.textContent = getSlotTypeShort(slot.slot_type);

            btn.append(idEl);
            if (vehicle) {
                const vehicleEl = document.createElement("span");
                vehicleEl.className = "lm-vehicle-icon";
                vehicleEl.textContent = vehicle.icon;
                vehicleEl.setAttribute("aria-hidden", "true");
                btn.append(vehicleEl);
            }
            btn.append(typeEl);
            grid.append(btn);
        });

        panel.append(zoneName, zoneCount, grid);
        container.append(panel);
    });

    if (selectedSlotId && parkingSlots) {
        const selected = parkingSlots.find((slot) => String(slot.slot_id) === selectedSlotId);
        const details = $("selectedSlotDetails");
        if (selected && (!selectedZone || String(selected.zone).toUpperCase() === selectedZone)) {
            renderSelectedSlot(selected);
        } else if (details) {
            details.hidden = true;
        }
    }
}

function renderSelectedSlot(slot) {
    const details = $("selectedSlotDetails");
    if (!details) return;

    const active = slot.is_active !== false;
    const status = active
        ? String(slot.current_status ?? "AVAILABLE").toLowerCase()
        : "inactive";
    const title = document.createElement("h3");
    title.textContent = `${slot.slot_id ?? "Parking space"} · Zone ${slot.zone ?? "—"}`;
    const summary = document.createElement("p");
    summary.textContent = `${status[0].toUpperCase()}${status.slice(1)} · ${getSlotTypeLabel(slot.slot_type)}`;
    details.replaceChildren(title, summary);
    details.hidden = false;
}

function updateReservationZoneOptions() {
    const slotTypeSelect = $("slotType");
    const zoneSelect = $("preferredZone");
    const hint = $("zoneAvailabilityHint");
    if (!slotTypeSelect || !zoneSelect || !hint || !Array.isArray(parkingSlots)) return;

    const selectedType = slotTypeSelect.value.toUpperCase();
    const compatibleZones = new Set(
        parkingSlots
            .filter((slot) =>
                slot.is_active !== false &&
                String(slot.slot_type ?? "REGULAR").toUpperCase() === selectedType
            )
            .map((slot) => String(slot.zone ?? "").toUpperCase())
    );

    Array.from(zoneSelect.options).forEach((option) => {
        if (!option.value) return;
        option.disabled = !compatibleZones.has(option.value.toUpperCase());
    });

    document.querySelectorAll("[data-zone-choice]").forEach((button) => {
        const zone = button.dataset.zoneChoice.toUpperCase();
        button.disabled = Boolean(zone && !compatibleZones.has(zone));
        button.setAttribute("aria-pressed", String(zone === zoneSelect.value.toUpperCase()));
    });

    const selectedZone = zoneSelect.value.toUpperCase();
    if (selectedZone && !compatibleZones.has(selectedZone)) {
        zoneSelect.value = "";
    }

    if (compatibleZones.size === 0) {
        hint.textContent = `No ${getSlotTypeLabel(selectedType).toLowerCase()} spaces are configured. Choose another parking type.`;
    } else {
        const zones = Array.from(compatibleZones)
            .sort()
            .map((zone) => `Zone ${zone}`)
            .join(", ");
        hint.textContent = `${getSlotTypeLabel(selectedType)} spaces are available in ${zones}. Choose any zone to let the system assign one.`;
    }
}

async function loadParkingSlots() {
    const container = $("slotsContainer");
    if (!container) return;

    setText("slotsMessage", "Loading parking slots...");

    try {
        const data = await fetchJSON("/api/slots");
        const slots = Array.isArray(data) ? data : data.slots;

        if (!Array.isArray(slots)) {
            throw new Error("The slots API returned an unexpected response.");
        }

        parkingSlots = slots;
        updateZoneAvailability(slots);
        updateReservationZoneOptions();
        renderLiveMap(slots);
        renderParkingSlots();

        if (slots.length === 0) {
            setText("slotsMessage", "No parking slots were returned.");
            return;
        }

        const availableCount = slots.filter((slot) =>
            String(slot.current_status ?? "").toUpperCase() === "AVAILABLE" &&
            slot.is_active !== false
        ).length;
        setText("slotsMessage", `${availableCount} of ${slots.length} spaces available now.`);
    } catch (error) {
        console.error("Parking slots request failed:", error);
        setText("slotsMessage", "Could not load parking slots. Check the backend and try refreshing.");
    }
}

/* ML FORECASTS */

function clearForecasts(message) {
    setText("forecast30", "—");
    setText("forecast60", "—");
    setText("forecast30Detail", "A valid prediction is not currently available.");
    setText("forecast60Detail", "A valid prediction is not currently available.");
    setText("forecastMessage", message);
    setText("dashboardFeatureTitle", "Live facility insight");
    setText("dashboardFeatureStatus", "Model unavailable");
    setText("dashboardFeatureMeta", "The trained occupancy model has not returned a usable forecast.");
}

function renderForecast(data) {
    if (data.status !== "success" || !Array.isArray(data.predictions)) {
        let message = data.message || "Forecasts are currently unavailable.";

        if (data.observations_available != null) {
            const have = data.observations_available;
            const need = data.observations_required ?? 5;
            message += ` (${have}/${need} real occupancy observations collected.)`;
        }

        clearForecasts(message);
        return;
    }

    setText("forecast30", "—");
    setText("forecast60", "—");
    let shortTermPrediction = null;

    data.predictions.forEach((prediction) => {
        const horizon = Number(prediction.forecast_minutes);
        if (horizon !== 30 && horizon !== 60) return;

        const occupied = Number(prediction.predicted_occupied);
        const percentage = Number(prediction.predicted_occupancy_pct);
        const suffix = horizon === 30 ? "30" : "60";

        if (!Number.isFinite(occupied) || !Number.isFinite(percentage)) {
            setText(`forecast${suffix}Detail`, "The API returned an invalid prediction.");
            return;
        }

        setText(`forecast${suffix}`, formatNumber(occupied));
        const baseline = Number(prediction.current_occupied);
        const delta = Number.isFinite(baseline) ? occupied - baseline : null;
        const comparison = delta == null
            ? ""
            : ` · ${delta > 0 ? "+" : ""}${formatNumber(delta)} vs sampled occupancy (${formatNumber(baseline)})`;
        setText(
            `forecast${suffix}Detail`,
            `${percentage.toFixed(1)}% predicted occupancy${comparison}`
        );
        if (horizon === 30) shortTermPrediction = prediction;
    });

    if (shortTermPrediction) {
        setText("dashboardFeatureTitle", "30-minute occupancy outlook");
        setText("dashboardFeatureStatus", "Model output");
        setText(
            "dashboardFeatureMeta",
            `${formatNumber(data.observations_available)} real occupancy observations · ${shortTermPrediction.model_name || "Trained forecast model"}`
        );
        setText(
            "dashboardInsight",
            `The model projects ${formatNumber(shortTermPrediction.predicted_occupied)} occupied spaces in 30 minutes (${Number(shortTermPrediction.predicted_occupancy_pct).toFixed(1)}% of capacity).`
        );
    } else {
        setText("dashboardFeatureTitle", "Live facility insight");
        setText("dashboardFeatureStatus", "Model unavailable");
        setText("dashboardFeatureMeta", "A 30-minute model forecast is not available in the latest response.");
    }

    setText("forecastMessage", "Forecast data received from the ML API.");
}

async function loadForecasts() {
    try {
        const data = await fetchJSON("/api/analytics/forecast");
        renderForecast(data);
    } catch (error) {
        console.error("Forecast request failed:", error);
        clearForecasts("Unable to contact the forecasting API.");
    }
}

async function loadModelStatus() {
    try {
        const data = await fetchJSON("/api/analytics/model-status");
        const models = Array.isArray(data.models) ? data.models : [];

        [30, 60].forEach((horizon) => {
            const model = models.find(
                (item) => Number(item.forecast_minutes) === horizon
            );
            const status = model?.available
                ? `${model.model_name} is packaged and ready. Five real occupancy observations are needed; scheduled data is collected every 15 minutes.`
                : "Trained model file is missing.";
            setText(`model${horizon}Status`, status);
        });
    } catch (error) {
        console.error("Model status request failed:", error);
        setText("model30Status", "Could not check model availability.");
        setText("model60Status", "Could not check model availability.");
    }
}

function createSvgElement(name, attributes = {}, text = "") {
    const element = document.createElementNS("http://www.w3.org/2000/svg", name);
    Object.entries(attributes).forEach(([key, value]) => {
        element.setAttribute(key, String(value));
    });
    if (text) element.textContent = text;
    return element;
}

function renderOccupancyTrend(trend, occupancy, predictions = []) {
    const chart = $("occupancyTrendChart");
    if (!chart) return;
    chart.replaceChildren();

    const points = Array.isArray(trend) ? trend.map((item) => ({
        label: item.timestamp,
        percentage: Number(item.occupancy_percentage),
        occupied: Number(item.occupied),
        capacity: Number(item.capacity)
    })).filter((item) => Number.isFinite(item.percentage)) : [];

    if (points.length === 0 && occupancy) {
        points.push({
            label: new Date().toISOString(),
            percentage: Number(occupancy.occupancy_percentage),
            occupied: Number(occupancy.occupied_slots),
            capacity: Number(occupancy.active_capacity)
        });
    }

    const width = 720;
    const height = 260;
    const left = 48;
    const right = 18;
    const top = 20;
    const bottom = 38;
    const plotWidth = width - left - right;
    const plotHeight = height - top - bottom;
    const validPredictions = predictions.map((item) => ({
        percentage: Number(item.predicted_occupancy_pct),
        minutes: Number(item.forecast_minutes)
    })).filter((item) => Number.isFinite(item.percentage) && Number.isFinite(item.minutes));
    const observedWidth = validPredictions.length ? plotWidth * 0.72 : plotWidth;
    const coordsFor = (items) => items.map((point, index) => ({
        x: left + (items.length === 1 ? observedWidth / 2 : index * observedWidth / (items.length - 1)),
        y: top + (100 - Math.min(100, Math.max(0, point.percentage))) * plotHeight / 100,
        ...point
    }));

    [0, 25, 50, 75, 100].forEach((value) => {
        const y = top + (100 - value) * plotHeight / 100;
        chart.append(
            createSvgElement("line", {
                x1: left, x2: width - right, y1: y, y2: y, class: "chart-grid-line"
            }),
            createSvgElement("text", {
                x: left - 10, y: y + 4, "text-anchor": "end", class: "chart-axis-label"
            }, `${value}%`)
        );
    });

    const observed = coordsFor(points);
    if (observed.length > 1) {
        chart.append(createSvgElement("polyline", {
            points: observed.map((point) => `${point.x},${point.y}`).join(" "),
            class: "chart-observed-line"
        }));
    }
    observed.forEach((point) => chart.append(createSvgElement("circle", {
        cx: point.x, cy: point.y, r: 4, class: "chart-observed-point"
    })));

    if (validPredictions.length && observed.length) {
        const latest = observed[observed.length - 1];
        const predictionPoints = [
            { x: latest.x, y: latest.y },
            ...validPredictions.map((item, index) => ({
                x: latest.x + (plotWidth - observedWidth) * (index + 1) / validPredictions.length,
                y: top + (100 - Math.min(100, Math.max(0, item.percentage))) * plotHeight / 100
            }))
        ];
        chart.append(createSvgElement("polyline", {
            points: predictionPoints.map((point) => `${point.x},${point.y}`).join(" "),
            class: "chart-predicted-line"
        }));
        predictionPoints.slice(1).forEach((point, index) => chart.append(
            createSvgElement("circle", {
                cx: point.x, cy: point.y, r: 4, class: "chart-predicted-point"
            }),
            createSvgElement("text", {
                x: point.x, y: Math.max(13, point.y - 11), "text-anchor": "middle", class: "chart-axis-label"
            }, `${validPredictions[index].minutes}m`)
        ));
    }

    if (points.length > 0) {
        const labelIndices = [...new Set([0, Math.floor((points.length - 1) / 2), points.length - 1])];
        labelIndices.forEach((index) => {
            const point = observed[index];
            const date = new Date(point.label);
            const label = Number.isNaN(date.getTime())
                ? `Snapshot ${index + 1}`
                : date.toLocaleTimeString([], { hour: "numeric", minute: "2-digit" });
            chart.append(createSvgElement("text", {
                x: point.x, y: height - 9, "text-anchor": "middle", class: "chart-axis-label"
            }, label));
        });
        const latest = points[points.length - 1];
        setText(
            "occupancyChartSummary",
            `${latest.percentage.toFixed(1)}% occupied now · ${points.length} live snapshot${points.length === 1 ? "" : "s"} in the last 24 hours.`
        );
    } else {
        setText("occupancyChartSummary", "No occupancy snapshots are available yet. New vehicle activity will build the trend.");
    }
}

function renderZoneUtilization(zones) {
    const chart = $("zoneUtilizationChart");
    if (!chart) return;
    chart.replaceChildren();

    const validZones = Array.isArray(zones) ? zones.filter((zone) =>
        Number(zone.active_capacity) > 0
    ) : [];
    if (!validZones.length) {
        chart.append(createSvgElement("text", {
            x: 260, y: 128, "text-anchor": "middle", class: "chart-axis-label"
        }, "No zone capacity data available"));
        return;
    }

    const barX = 112;
    const barWidth = 360;
    const rowHeight = 54;
    validZones.forEach((zone, index) => {
        const y = 28 + index * rowHeight;
        const capacity = Number(zone.active_capacity);
        const occupied = Math.min(capacity, Math.max(0, Number(zone.occupied_slots) || 0));
        const available = Math.max(0, capacity - occupied);
        const occupiedWidth = barWidth * occupied / capacity;
        chart.append(
            createSvgElement("text", {
                x: 8, y: y + 18, class: "chart-zone-label"
            }, `Zone ${zone.zone}`),
            createSvgElement("rect", {
                x: barX, y, width: barWidth, height: 18, rx: 9, class: "chart-zone-track"
            }),
            createSvgElement("rect", {
                x: barX, y, width: occupiedWidth, height: 18, rx: 9, class: "chart-zone-occupied"
            }),
            createSvgElement("text", {
                x: barX, y: y + 37, class: "chart-axis-label"
            }, `${occupied} occupied · ${available} available of ${capacity}`)
        );
    });
}

function formatLocalDateTime(value) {
    const date = new Date(value);
    return Number.isNaN(date.getTime())
        ? "Time unavailable"
        : date.toLocaleString([], {
            month: "short", day: "numeric", hour: "numeric", minute: "2-digit"
        });
}

