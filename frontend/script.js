function renderParkingIntelligence(intelligence, occupancyData, forecastData) {
    const summary = intelligence.summary || {};
    const alerts = Array.isArray(intelligence.alerts) ? intelligence.alerts : [];
    const releases = Array.isArray(intelligence.estimated_releases)
        ? intelligence.estimated_releases
        : [];
    const predictions = forecastData?.status === "success" &&
        Array.isArray(forecastData.predictions)
        ? forecastData.predictions
        : [];

    renderOccupancyTrend(
        intelligence.trend,
        intelligence.occupancy,
        predictions
    );
    renderZoneUtilization(occupancyData.zones);

    setText("intelOverstayCount", formatNumber(summary.overstays ?? 0));
    setText("intelUnusedCount", formatNumber(summary.unused_at_risk ?? 0));
    if (releases.length) {
        const next = releases[0];
        setText("intelNextRelease", formatLocalDateTime(next.estimated_available_at));
        setText(
            "intelNextReleaseDetail",
            `${next.slot_id} · ${next.confidence.toLowerCase()} confidence`
        );
    } else {
        setText("intelNextRelease", "No active sessions");
        setText("intelNextReleaseDetail", "Estimated releases appear after vehicle entry");
    }

    const alertList = $("intelligenceAlerts");
    alertList?.replaceChildren();
    if (alertList) {
        if (!alerts.length) {
            alertList.append(makeIntelRow(
                "All clear",
                "No late departures or reservations at arrival risk right now.",
                "CLEAR",
                "tag-clear"
            ));
        } else {
            alerts.forEach((alert) => {
                const title = `${alert.slot_id} · ${alert.vehicle_no}`;
                const detail = `${alert.message} Zone ${alert.zone}.`;
                alertList.append(makeIntelRow(
                    title,
                    detail,
                    alert.kind.replaceAll("_", " "),
                    alert.severity === "HIGH" ? "tag-high" :
                        alert.severity === "MEDIUM" ? "tag-medium" : "tag-low"
                ));
            });
        }
    }

    const releaseList = $("estimatedReleases");
    releaseList?.replaceChildren();
    if (releaseList) {
        if (!releases.length) {
            releaseList.append(makeIntelRow(
                "No checked-in vehicles",
                "Space release estimates appear here after a vehicle checks in.",
                "LIVE",
                "tag-clear"
            ));
        } else {
            releases.forEach((release) => {
                releaseList.append(makeIntelRow(
                    `${release.slot_id} · ${formatLocalDateTime(release.estimated_available_at)}`,
                    `${release.estimate_basis} Zone ${release.zone}.`,
                    `${release.confidence} CONFIDENCE`,
                    release.confidence === "MEDIUM" ? "tag-medium" : "tag-low"
                ));
            });
        }
    }

    const sampleCount = Number(summary.historical_overstay_samples) || 0;
    setText(
        "intelligenceMessage",
        `${alerts.length} reservation insight${alerts.length === 1 ? "" : "s"} · ` +
        (sampleCount
            ? `release estimates use ${sampleCount} completed overstay record${sampleCount === 1 ? "" : "s"} (median ${summary.median_overstay_minutes} min).`
            : "release estimates use scheduled end times; confidence will improve as completed sessions build history.")
    );
}

async function loadParkingIntelligence() {
    const message = $("intelligenceMessage");
    if (message) message.textContent = "Analyzing live occupancy and reservations…";
    try {
        const [intelligence, occupancyData, forecastData] = await Promise.all([
            fetchJSON("/api/analytics/intelligence"),
            fetchJSON("/api/analytics/occupancy"),
            fetchJSON("/api/analytics/forecast").catch((error) => {
                console.warn("Forecast overlay unavailable:", error);
                return null;
            })
        ]);
        if (forecastData) renderForecast(forecastData);
        else clearForecasts("Occupancy forecasts are unavailable right now.");
        renderParkingIntelligence(intelligence, occupancyData, forecastData);
    } catch (error) {
        console.error("Parking intelligence request failed:", error);
        setText("intelligenceMessage", "Unable to load parking intelligence. Please refresh or check the backend connection.");
    }
}

function localDateTimeValue(date) {
    const local = new Date(date.getTime() - date.getTimezoneOffset() * 60_000);
    return local.toISOString().slice(0, 16);
}

