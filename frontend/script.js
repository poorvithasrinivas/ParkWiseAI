
const API_BASE = "http://127.0.0.1:5000";

const $ = (id) => document.getElementById(id);
let parkingSlots = null;
let displayedSlots = [];

function setText(id, value) {
    const element = $(id);
    if (element) element.textContent = value;
}

async function fetchJSON(path, options = {}) {
    const response = await fetch(`${API_BASE}${path}`, options);
    const data = await response.json().catch(() => ({}));

    if (!response.ok) {
        const errorBody = data?.error;
        const message =
            data?.message ||
            (typeof errorBody === "string" ? errorBody : errorBody?.message) ||
            `Request failed (${response.status})`;

        const error = new Error(message);
        error.code = typeof errorBody === "object" ? errorBody.code : undefined;
        throw error;
    }

    return data;
}

function formatNumber(value) {
    const number = Number(value);
    return Number.isFinite(number) ? number.toLocaleString() : "—";
}

/* NAVIGATION */

const pageDetails = {
    dashboard: {
        title: "Parking overview",
        subtitle: "Monitor parking availability and AI-powered occupancy forecasts."
    },
    parking: {
        title: "Parking spaces",
        subtitle: "Explore campus parking zones and their availability."
    },
    forecast: {
        title: "AI forecasts",
        subtitle: "View predictions generated by the trained ML models."
    },
    reservations: {
        title: "Reservations",
        subtitle: "Reserve and manage campus parking."
    }
};

function showPage(pageName) {
    if (!pageDetails[pageName]) pageName = "dashboard";

    document.querySelectorAll(".page-view").forEach((page) => {
        page.hidden = page.dataset.view !== pageName;
    });

    document.querySelectorAll(".nav-item[data-page]").forEach((link) => {
        const active = link.dataset.page === pageName;
        link.classList.toggle("active", active);

        if (active) link.setAttribute("aria-current", "page");
        else link.removeAttribute("aria-current");
    });

    setText("pageTitle", pageDetails[pageName].title);
    setText("pageSubtitle", pageDetails[pageName].subtitle);

    if (pageName === "dashboard") loadLiveStats();
    if (pageName === "parking") {
        loadLiveStats();
        loadParkingSlots();
    }
    if (pageName === "forecast") loadForecasts();
}

function initializeNavigation() {
    document.querySelectorAll(".nav-item[data-page]").forEach((link) => {
        link.addEventListener("click", (event) => {
            event.preventDefault();
            const pageName = link.dataset.page;

            if (location.hash !== `#${pageName}`) {
                history.pushState(null, "", `#${pageName}`);
            }

            showPage(pageName);
        });
    });

    document.querySelector(".brand")?.addEventListener("click", (event) => {
        event.preventDefault();
        history.pushState(null, "", "#dashboard");
        showPage("dashboard");
    });

    window.addEventListener("popstate", () => {
        showPage(location.hash.slice(1) || "dashboard");
    });

    showPage(location.hash.slice(1) || "dashboard");
}

/* CONNECTION STATUS */

function setConnection(connected, message) {
    setText("connectionText", message);

    document.querySelectorAll(".connection-status .status-dot").forEach((dot) => {
        dot.style.background = connected ? "#13a678" : "#e05260";
    });
}

/* LIVE OCCUPANCY */

function renderLiveStats(data) {
    const occupancy = data.occupancy;

    if (!occupancy) {
        setText("liveMessage", "Occupancy data was not found in the API response.");
        return;
    }

    const capacity = Number(occupancy.active_capacity);
    const occupied = Number(occupancy.occupied_slots);
    const available = Number(occupancy.available_slots);
    const percentage = Number(occupancy.occupancy_percentage);

    if (![capacity, occupied, available, percentage].every(Number.isFinite)) {
        setText("liveMessage", "The backend returned invalid occupancy values.");
        return;
    }

    setText("totalCapacity", formatNumber(capacity));
    setText("occupiedCount", formatNumber(occupied));
    setText("availableCount", formatNumber(available));
    setText("occupancyRate", `${percentage.toFixed(1)}%`);
    setText("occupancyBarLabel", `${percentage.toFixed(1)}%`);

    const safePercentage = Math.max(0, Math.min(100, percentage));
    const bar = $("occupancyBar");
    const progress = $("occupancyProgress");

    if (bar) bar.style.width = `${safePercentage}%`;

    if (progress) {
        progress.setAttribute("aria-valuenow", String(safePercentage));
    }

    if (Array.isArray(data.zones)) {
        data.zones.forEach((zone) => {
            const name = String(zone.zone ?? "").toUpperCase();

            if (["A", "B", "C"].includes(name)) {
                setText(`zone${name}`, `${formatNumber(zone.active_capacity)} spaces`);
            }
        });
    }

    setText("liveMessage", "Live parking data received from the backend.");
    setText("lastUpdated", `Last checked: ${new Date().toLocaleTimeString()}`);
}

async function loadLiveStats() {
    try {
        const data = await fetchJSON("/api/analytics/occupancy");
        renderLiveStats(data);
        setConnection(true, "Backend connected");
    } catch (error) {
        console.error("Occupancy request failed:", error);
        setConnection(false, "Backend unavailable");
        setText("liveMessage", "Unable to load live parking data. Check that the backend is running.");
    }
}

/* PARKING SLOT DISPLAY */

function updateZoneAvailability(slots) {
    ["A", "B", "C"].forEach((zone) => {
        const zoneSlots = slots.filter((slot) =>
            String(slot.zone ?? "").toUpperCase() === zone &&
            slot.is_active !== false
        );
        const available = zoneSlots.filter((slot) =>
            String(slot.current_status ?? "").toUpperCase() === "AVAILABLE"
        ).length;

        setText(
            `zone${zone}Availability`,
            `${formatNumber(available)} available now`
        );
    });
}

function getSlotTypeLabel(slotType) {
    const labels = {
        REGULAR: "Regular",
        EV: "EV charging",
        ACCESSIBLE: "Accessible"
    };

    return labels[String(slotType ?? "").toUpperCase()] || "Standard";
}

function renderParkingSlots() {
    const container = $("slotsContainer");
    if (!container || !Array.isArray(parkingSlots)) return;

    const zoneFilter = $("slotZoneFilter")?.value ?? "";
    const typeFilter = $("slotTypeFilter")?.value ?? "";
    const statusFilter = $("slotStatusFilter")?.value ?? "";
    displayedSlots = parkingSlots.filter((slot) => {
        const zone = String(slot.zone ?? "").toUpperCase();
        const type = String(slot.slot_type ?? "REGULAR").toUpperCase();
        const status = String(slot.current_status ?? "AVAILABLE").toUpperCase();

        return (!zoneFilter || zone === zoneFilter) &&
            (!typeFilter || type === typeFilter) &&
            (!statusFilter || status === statusFilter);
    });

    container.replaceChildren();
    setText("slotsTotal", `${displayedSlots.length} of ${parkingSlots.length} spaces`);

    if (displayedSlots.length === 0) {
        const emptyState = document.createElement("p");
        emptyState.className = "slot-empty-state";
        emptyState.textContent = "No parking spaces match these filters.";
        container.append(emptyState);
        return;
    }

    const grid = document.createElement("div");
    grid.className = "parking-slot-grid";

    displayedSlots.forEach((slot) => {
        const slotType = String(slot.slot_type ?? "REGULAR").toUpperCase();
        const status = String(slot.current_status ?? "AVAILABLE").toUpperCase();
        const available = status === "AVAILABLE" && slot.is_active !== false;
        const card = document.createElement("article");
        card.className = `parking-slot-card ${available ? "is-available" : "is-occupied"}`;

        const cardTop = document.createElement("div");
        cardTop.className = "parking-slot-card-top";

        const icon = document.createElement("span");
        icon.className = "parking-slot-icon";
        icon.setAttribute("aria-hidden", "true");
        icon.textContent = "P";

        const statusBadge = document.createElement("span");
        statusBadge.className = `slot-status ${available ? "available" : "occupied"}`;
        statusBadge.textContent = available ? "Available" : "Occupied";
        cardTop.append(icon, statusBadge);

        const slotName = document.createElement("h3");
        slotName.textContent = slot.slot_id ?? "Unnamed space";

        const details = document.createElement("p");
        details.textContent = `Zone ${slot.zone ?? "—"} · ${getSlotTypeLabel(slotType)}`;

        const typeBadge = document.createElement("span");
        typeBadge.className = `slot-type-badge slot-type-${slotType.toLowerCase()}`;
        typeBadge.textContent = getSlotTypeLabel(slotType);

        card.append(cardTop, slotName, details, typeBadge);
        grid.append(card);
    });

    container.append(grid);
}

function updateReservationZoneOptions() {
    const slotTypeSelect = $("slotType");
    const zoneSelect = $("preferredZone");
    const hint = $("zoneAvailabilityHint");
    if (!slotTypeSelect || !zoneSelect || !hint || !Array.isArray(parkingSlots)) return;

    const selectedType = slotTypeSelect.value.toUpperCase();
    const compatibleZones = new Set(
        parkingSlots
            .filter((slot) =>
                slot.is_active !== false &&
                String(slot.slot_type ?? "REGULAR").toUpperCase() === selectedType
            )
            .map((slot) => String(slot.zone ?? "").toUpperCase())
    );

    Array.from(zoneSelect.options).forEach((option) => {
        if (!option.value) return;
        option.disabled = !compatibleZones.has(option.value.toUpperCase());
    });

    const selectedZone = zoneSelect.value.toUpperCase();
    if (selectedZone && !compatibleZones.has(selectedZone)) {
        zoneSelect.value = "";
    }

    if (compatibleZones.size === 0) {
        hint.textContent = `No ${getSlotTypeLabel(selectedType).toLowerCase()} spaces are configured. Choose another parking type.`;
    } else {
        const zones = Array.from(compatibleZones)
            .sort()
            .map((zone) => `Zone ${zone}`)
            .join(", ");
        hint.textContent = `${getSlotTypeLabel(selectedType)} spaces are available in ${zones}. Choose any zone to let the system assign one.`;
    }
}

async function loadParkingSlots() {
    const container = $("slotsContainer");
    if (!container) return;

    setText("slotsMessage", "Loading parking slots...");

    try {
        const data = await fetchJSON("/api/slots");
        const slots = Array.isArray(data) ? data : data.slots;

        if (!Array.isArray(slots)) {
            throw new Error("The slots API returned an unexpected response.");
        }

        parkingSlots = slots;
        updateZoneAvailability(slots);
        updateReservationZoneOptions();
        renderParkingSlots();

        if (slots.length === 0) {
            setText("slotsMessage", "No parking slots were returned.");
            return;
        }

        const availableCount = slots.filter((slot) =>
            String(slot.current_status ?? "").toUpperCase() === "AVAILABLE" &&
            slot.is_active !== false
        ).length;
        setText("slotsMessage", `${availableCount} of ${slots.length} spaces available now.`);
    } catch (error) {
        console.error("Parking slots request failed:", error);
        setText("slotsMessage", "Could not load parking slots. Check the backend and try refreshing.");
    }
}

/* ML FORECASTS */

function clearForecasts(message) {
    setText("forecast30", "—");
    setText("forecast60", "—");
    setText("forecast30Detail", "A valid prediction is not currently available.");
    setText("forecast60Detail", "A valid prediction is not currently available.");
    setText("forecastMessage", message);
}

function renderForecast(data) {
    if (data.status !== "success" || !Array.isArray(data.predictions)) {
        let message = data.message || "Forecasts are currently unavailable.";

        if (data.observations_available != null) {
            message += ` (${data.observations_available}/${data.observations_required ?? 5} observations available.)`;
        }

        clearForecasts(message);
        return;
    }

    setText("forecast30", "—");
    setText("forecast60", "—");

    data.predictions.forEach((prediction) => {
        const horizon = Number(prediction.forecast_minutes);
        if (horizon !== 30 && horizon !== 60) return;

        const occupied = Number(prediction.predicted_occupied);
        const percentage = Number(prediction.predicted_occupancy_pct);
        const suffix = horizon === 30 ? "30" : "60";

        if (!Number.isFinite(occupied) || !Number.isFinite(percentage)) {
            setText(`forecast${suffix}Detail`, "The API returned an invalid prediction.");
            return;
        }

        setText(`forecast${suffix}`, formatNumber(occupied));
        setText(`forecast${suffix}Detail`, `${percentage.toFixed(1)}% predicted occupancy`);
    });

    setText("forecastMessage", "Forecast data received from the ML API.");
}

async function loadForecasts() {
    try {
        const data = await fetchJSON("/api/analytics/forecast");
        renderForecast(data);
    } catch (error) {
        console.error("Forecast request failed:", error);
        clearForecasts("Unable to contact the forecasting API.");
    }
}

/* RESERVATION FORM */

function initializeReservationForm() {
    const form = $("reservationForm");
    if (!form) return;

    const startInput = $("startTime");
    const endInput = $("endTime");
    const submitButton = $("reserveButton");
    const slotTypeSelect = $("slotType");

    slotTypeSelect?.addEventListener("change", updateReservationZoneOptions);

    function updateEndMinimum() {
        if (startInput && endInput) {
            endInput.min = startInput.value;
        }
    }

    startInput?.addEventListener("change", updateEndMinimum);

    let clearOnReset = false;

    form.addEventListener("reset", () => {
        if (!clearOnReset) return;

        setText("reservationMessage", "");
        const result = $("reservationResult");
        if (result) result.replaceChildren();
        clearOnReset = false;
    });

    $("resetReservationButton")?.addEventListener("click", () => {
        clearOnReset = true;
    });

    form.addEventListener("submit", async (event) => {
        event.preventDefault();

        const vehicleNo = $("vehicleNo")?.value.trim().toUpperCase();
        const vehicleType = $("vehicleType")?.value;
        const slotType = $("slotType")?.value;
        const zone = $("preferredZone")?.value ?? "";
        const startValue = startInput?.value;
        const endValue = endInput?.value;

        if (!vehicleNo || !startValue || !endValue) {
            setText("reservationMessage", "Please complete all required fields.");
            return;
        }

        if (zone && Array.isArray(parkingSlots)) {
            const compatibleZoneExists = parkingSlots.some((slot) =>
                slot.is_active !== false &&
                String(slot.zone ?? "").toUpperCase() === zone.toUpperCase() &&
                String(slot.slot_type ?? "REGULAR").toUpperCase() === String(slotType).toUpperCase()
            );

            if (!compatibleZoneExists) {
                setText(
                    "reservationMessage",
                    `${getSlotTypeLabel(slotType)} spaces are not configured in Zone ${zone}. Choose an available zone or select any zone.`
                );
                return;
            }
        }

        if (!/^[A-Za-z0-9][A-Za-z0-9 -]{2,14}$/.test(vehicleNo)) {
            setText("reservationMessage", "Vehicle registration number must be 4–15 letters, numbers, spaces or hyphens.");
            return;
        }

        const start = new Date(startValue);
        const end = new Date(endValue);

        if (Number.isNaN(start.getTime()) || Number.isNaN(end.getTime()) || end <= start) {
            setText("reservationMessage", "End time must be later than start time.");
            return;
        }

        if (start < new Date()) {
            setText("reservationMessage", "Please select a start time in the future.");
            return;
        }

        const originalLabel = submitButton?.textContent;

        if (submitButton) {
            submitButton.disabled = true;
            submitButton.textContent = "Booking...";
        }

        setText("reservationMessage", "Submitting your reservation...");

        const resultContainer = $("reservationResult");
        if (resultContainer) resultContainer.replaceChildren();

        try {
            const booking = await fetchJSON("/api/reservations", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                    vehicle_no: vehicleNo,
                    vehicle_type: vehicleType,
                    slot_type: slotType,
                    zone,
                    start_time: start.toISOString(),
                    end_time: end.toISOString()
                })
            });

            form.reset();
            updateEndMinimum();

            if (resultContainer) {
                const heading = document.createElement("h3");
                heading.textContent = "Booking confirmed";

                const details = document.createElement("p");
                details.textContent =
                    `Reservation: ${booking.reservation_id ?? "—"} · ` +
                    `Slot: ${booking.slot_id ?? "—"} · ` +
                    `Zone: ${booking.zone ?? "—"} · ` +
                    `Status: ${booking.status ?? "CONFIRMED"}`;

                resultContainer.append(heading, details);
            }

            setText("reservationMessage", "Reservation confirmed!");
            loadParkingSlots();
            loadLiveStats();
        } catch (error) {
            console.error("Reservation failed:", error);
            const message = error.code === "NO_AVAILABLE_SLOT"
                ? "No matching space is free for that time. Try a different time, zone, or parking type."
                : error.message;
            setText("reservationMessage", `Booking failed: ${message}`);
        } finally {
            if (submitButton) {
                submitButton.disabled = false;
                submitButton.textContent = originalLabel || "Confirm reservation";
            }
        }
    });

    updateEndMinimum();
}

/* REFRESH */

let refreshInProgress = false;

async function refreshDashboard() {
    if (refreshInProgress) return;

    refreshInProgress = true;
    const button = $("refreshButton");

    if (button) {
        button.disabled = true;
        button.textContent = "Refreshing...";
    }

    try {
        await Promise.all([loadLiveStats(), loadForecasts()]);
        await loadParkingSlots();
    } finally {
        refreshInProgress = false;

        if (button) {
            button.disabled = false;
            button.textContent = "↻ Refresh data";
        }
    }
}

/* INITIALIZATION */

document.addEventListener("DOMContentLoaded", () => {
    initializeNavigation();
    initializeReservationForm();

    ["slotZoneFilter", "slotTypeFilter", "slotStatusFilter"].forEach((id) => {
        $(id)?.addEventListener("change", renderParkingSlots);
    });

    $("refreshButton")?.addEventListener("click", refreshDashboard);

    document.querySelectorAll("[data-refresh]").forEach((button) => {
        button.addEventListener("click", refreshDashboard);
    });

    loadLiveStats();
    loadParkingSlots();
    window.setInterval(refreshDashboard, 60_000);
});
