async function sendCopilotMessage(message) {
    if (copilotRequestActive || !message.trim()) return;
    copilotRequestActive = true;
    const generation = copilotGeneration;
    const input = $("copilotInput");
    const sendButton = $("copilotSend");
    const typing = $("copilotTyping");
    appendCopilotMessage("user", message);
    if (input) input.value = "";
    if (sendButton) sendButton.disabled = true;
    if (typing) typing.hidden = false;
    scrollCopilotToLatest();

    const controller = new AbortController();
    const timeout = window.setTimeout(() => controller.abort(), 15_000);
    try {
        const data = await fetchJSON("/api/chat", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            signal: controller.signal,
            body: JSON.stringify({
                message,
                chat_id: copilotChatId,
                timezone_offset_minutes: -new Date().getTimezoneOffset(),
            }),
        });
        if (generation !== copilotGeneration) return;
        copilotChatId = data.chat_id || copilotChatId;
        appendCopilotMessage("assistant", data.reply, data.actions);
    } catch (error) {
        console.error("ParkWise Copilot request failed:", error);
        if (generation !== copilotGeneration) return;
        const messageText = error.name === "AbortError"
            ? "That request took too long. Please try again."
            : `I couldn't reach ParkWise data: ${error.message}`;
        appendCopilotMessage("assistant", messageText);
    } finally {
        window.clearTimeout(timeout);
        if (typing) typing.hidden = true;
        if (sendButton) sendButton.disabled = false;
        copilotRequestActive = false;
        input?.focus();
    }
}

