function formatVehicleDetailTime(value) {
    if (!value) return "Not recorded";
    const date = new Date(value);
    return Number.isNaN(date.getTime())
        ? "Time unavailable"
        : date.toLocaleString([], {
            year: "numeric",
            month: "short",
            day: "numeric",
            hour: "numeric",
            minute: "2-digit"
        });
}

function showReservationDetails(reservationId) {
    const reservation = activeReservations.find(
        (item) => item.reservation_id === reservationId
    );
    const dialog = $("reservationDetailDialog");
    if (!reservation || !dialog) return;

    const vehicleTypeLabels = {
        CAR: "Car",
        BIKE: "Bike",
        MOTORCYCLE: "Motorcycle",
        EV: "Electric vehicle"
    };
    const slotTypeLabels = {
        REGULAR: "Regular",
        EV: "EV",
        ACCESSIBLE: "Accessible"
    };
    const status = reservation.status.toLowerCase().replaceAll("_", " ");
    const fields = {
        detailReservationId: reservation.reservation_id,
        detailVehicleNo: reservation.vehicle_no,
        detailVehicleType: vehicleTypeLabels[reservation.vehicle_type] || reservation.vehicle_type,
        detailSlotId: reservation.slot_id,
        detailZone: `Zone ${reservation.zone}`,
        detailSlotType: slotTypeLabels[reservation.slot_type] || reservation.slot_type,
        detailStatus: status.replace(/\b\w/g, (letter) => letter.toUpperCase()),
        detailCreatedAt: formatVehicleDetailTime(reservation.created_at),
        detailStartTime: formatVehicleDetailTime(reservation.start_time),
        detailEndTime: formatVehicleDetailTime(reservation.end_time),
        detailEntryTime: formatVehicleDetailTime(reservation.entry_time),
        detailExitTime: formatVehicleDetailTime(reservation.exit_time)
    };
    Object.entries(fields).forEach(([id, value]) => setText(id, value || "Not available"));
    setText("reservationDetailTitle", `${reservation.vehicle_no} · Reservation`);

    if (!dialog.open) dialog.showModal();
}

async function loadActiveReservations() {
    setText("activeReservationsMessage", "Loading active reservations...");

    try {
        const data = await fetchJSON("/api/reservations?status=ACTIVE");
        if (!Array.isArray(data.reservations)) {
            throw new Error("The reservations API returned an unexpected response.");
        }
        renderActiveReservations(data.reservations);
    } catch (error) {
        console.error("Active reservations request failed:", error);
        setText(
            "activeReservationsMessage",
            "Could not load active reservations. Check the backend and refresh."
        );
    }
}

async function recordVehicleMovement(reservationId, movement, button) {
    if (!reservationId) {
        setText("movementMessage", "Enter a reservation ID first.");
        return;
    }

    const actionName = movement === "entry" ? "entry" : "exit";
    const originalLabel = button?.textContent;
    if (button) {
        button.disabled = true;
        button.textContent = movement === "entry" ? "Checking in…" : "Checking out…";
    }
    setText("movementMessage", `Recording vehicle ${actionName}…`);

    try {
        const result = await fetchJSON(`/api/${actionName}`, {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ reservation_id: reservationId })
        });
        setText(
            "movementMessage",
            `Vehicle ${actionName} recorded: ${result.vehicle_no || reservationId} · ` +
            `${result.slot_id} · ${result.status}. Live occupancy is updating.`
        );

        const input = $("movementReservationId");
        if (input) input.value = "";
        await Promise.all([
            loadActiveReservations(),
            loadParkingSlots(),
            loadLiveStats()
        ]);
    } catch (error) {
        console.error(`Vehicle ${actionName} failed:`, error);
        setText("movementMessage", `Could not record ${actionName}: ${error.message}`);
        await loadActiveReservations();
    } finally {
        if (button) {
            button.disabled = false;
            button.textContent = originalLabel || (
                movement === "entry" ? "Record vehicle entry" : "Record vehicle exit"
            );
        }
    }
}

function initializeVehicleManagement() {
    const form = $("vehicleMovementForm");
    form?.addEventListener("submit", async (event) => {
        event.preventDefault();
        const movement = event.submitter?.dataset.movement;
        if (!movement) {
            setText("movementMessage", "Choose whether to record entry or exit.");
            return;
        }
        await recordVehicleMovement(
            $("movementReservationId")?.value.trim(),
            movement,
            event.submitter
        );
    });

    $("activeReservationsContainer")?.addEventListener("click", async (event) => {
        const button = event.target.closest("button[data-reservation-id]");
        if (button) {
            await recordVehicleMovement(
                button.dataset.reservationId,
                button.dataset.movement,
                button
            );
            return;
        }
        const card = event.target.closest("[data-reservation-details]");
        if (card) showReservationDetails(card.dataset.reservationDetails);
    });

    $("activeReservationsContainer")?.addEventListener("keydown", (event) => {
        if (event.target.closest("button")) return;
        if (event.key !== "Enter" && event.key !== " ") return;
        const card = event.target.closest("[data-reservation-details]");
        if (!card) return;
        event.preventDefault();
        showReservationDetails(card.dataset.reservationDetails);
    });

    const detailsDialog = $("reservationDetailDialog");
    $("reservationDetailClose")?.addEventListener("click", () => detailsDialog?.close());
    detailsDialog?.addEventListener("click", (event) => {
        if (event.target === detailsDialog) detailsDialog.close();
    });

    $("refreshReservationsBtn")?.addEventListener("click", loadActiveReservations);
}

/* RESERVATION FORM */

function initializeReservationForm() {
    const form = $("reservationForm");
    if (!form) return;

    const startInput = $("startTime");
    const endInput = $("endTime");
    const submitButton = $("reserveButton");
    const slotTypeSelect = $("slotType");
    const zoneSelect = $("preferredZone");

    const clearPreferredSlot = () => {
        const preferredSlot = $("preferredSlotId");
        if (preferredSlot) preferredSlot.value = "";
    };
    slotTypeSelect?.addEventListener("change", () => {
        clearPreferredSlot();
        updateReservationZoneOptions();
    });
    zoneSelect?.addEventListener("change", () => {
        clearPreferredSlot();
        updateReservationZoneOptions();
    });
    startInput?.addEventListener("change", clearPreferredSlot);
    endInput?.addEventListener("change", clearPreferredSlot);
    document.querySelectorAll("[data-zone-choice]").forEach((button) => {
        button.addEventListener("click", () => {
            if (!zoneSelect || button.disabled) return;
            clearPreferredSlot();
            zoneSelect.value = button.dataset.zoneChoice;
            updateReservationZoneOptions();
        });
    });

    function updateEndMinimum() {
        if (startInput && endInput) {
            endInput.min = startInput.value;
        }
    }

    startInput?.addEventListener("change", updateEndMinimum);

    let clearOnReset = false;

    form.addEventListener("reset", () => {
        if (!clearOnReset) return;

        setText("reservationMessage", "");
        const result = $("reservationResult");
        if (result) result.replaceChildren();
        clearOnReset = false;
    });
    form.addEventListener("reset", () => {
        window.setTimeout(updateReservationZoneOptions, 0);
    });

    $("resetReservationButton")?.addEventListener("click", () => {
        clearOnReset = true;
    });

    form.addEventListener("submit", async (event) => {
        event.preventDefault();

        const vehicleNo = $("vehicleNo")?.value.trim().toUpperCase();
        const vehicleType = $("vehicleType")?.value;
        const slotType = $("slotType")?.value;
        const zone = $("preferredZone")?.value ?? "";
        const startValue = startInput?.value;
        const endValue = endInput?.value;

        if (!vehicleNo || !startValue || !endValue) {
            setText("reservationMessage", "Please complete all required fields.");
            return;
        }

        if (zone && Array.isArray(parkingSlots)) {
            const compatibleZoneExists = parkingSlots.some((slot) =>
                slot.is_active !== false &&
                String(slot.zone ?? "").toUpperCase() === zone.toUpperCase() &&
                String(slot.slot_type ?? "REGULAR").toUpperCase() === String(slotType).toUpperCase()
            );

            if (!compatibleZoneExists) {
                setText(
                    "reservationMessage",
                    `${getSlotTypeLabel(slotType)} spaces are not configured in Zone ${zone}. Choose an available zone or select any zone.`
                );
                return;
            }
        }

        if (!/^[A-Za-z0-9][A-Za-z0-9 -]{2,14}$/.test(vehicleNo)) {
            setText("reservationMessage", "Vehicle registration number must be 4–15 letters, numbers, spaces or hyphens.");
            return;
        }

        const start = new Date(startValue);
        const end = new Date(endValue);

        if (Number.isNaN(start.getTime()) || Number.isNaN(end.getTime()) || end <= start) {
            setText("reservationMessage", "End time must be later than start time.");
            return;
        }

        if (start < new Date()) {
            setText("reservationMessage", "Please select a start time in the future.");
            return;
        }

        const originalLabel = submitButton?.textContent;

        if (submitButton) {
            submitButton.disabled = true;
            submitButton.textContent = "Booking...";
        }

        setText("reservationMessage", "Submitting your reservation...");

        const resultContainer = $("reservationResult");
        if (resultContainer) resultContainer.replaceChildren();

        try {
            const booking = await fetchJSON("/api/reservations", {
                method: "POST",
                headers: { "Content-Type": "application/json" },
                body: JSON.stringify({
                    vehicle_no: vehicleNo,
                    vehicle_type: vehicleType,
                    slot_type: slotType,
                    zone,
                    preferred_slot_id: $("preferredSlotId")?.value ?? "",
                    start_time: start.toISOString(),
                    end_time: end.toISOString()
                })
            });

            form.reset();
            updateEndMinimum();
            updateReservationZoneOptions();

            if (resultContainer) {
                const heading = document.createElement("h3");
                heading.textContent = "Booking confirmed";

                const details = document.createElement("p");
                details.textContent =
                    `Reservation: ${booking.reservation_id ?? "—"} · ` +
                    `Slot: ${booking.slot_id ?? "—"} · ` +
                    `Zone: ${booking.zone ?? "—"} · ` +
                    `Status: ${booking.status ?? "CONFIRMED"}`;

                resultContainer.append(heading, details);
            }

            setText("reservationMessage", "Reservation confirmed!");
            loadParkingSlots();
            loadLiveStats();
        } catch (error) {
            console.error("Reservation failed:", error);
            const message = error.code === "NO_AVAILABLE_SLOT"
                ? "No matching space is free for that time. Try a different time, zone, or parking type."
                : error.message;
            setText("reservationMessage", `Booking failed: ${message}`);
        } finally {
            if (submitButton) {
                submitButton.disabled = false;
                submitButton.textContent = originalLabel || "Confirm reservation";
            }
        }
    });

    updateEndMinimum();
}

/* REFRESH */

let refreshInProgress = false;

async function refreshDashboard() {
    if (refreshInProgress) return;

    refreshInProgress = true;
    const button = $("refreshButton");

    if (button) {
        button.disabled = true;
        button.textContent = "Refreshing...";
    }

    try {
        const refreshes = [
            loadLiveStats(),
            loadModelStatus(),
            location.hash === "#forecast"
                ? loadParkingIntelligence()
                : loadForecasts()
        ];
        await Promise.all(refreshes);
        await loadParkingSlots();
    } finally {
        refreshInProgress = false;

        if (button) {
            button.disabled = false;
            button.textContent = "↻ Refresh data";
        }
    }
}

