function appendCopilotMessage(role, text, actions = []) {
    const container = $("copilotMessages");
    if (!container) return;
    const article = document.createElement("article");
    article.className = `copilot-message ${role === "user" ? "user-message" : "assistant-message"}`;
    const bubble = document.createElement("div");
    bubble.className = "copilot-bubble";
    bubble.textContent = text;
    article.append(bubble);

    if (role !== "user" && Array.isArray(actions) && actions.length) {
        const actionGroup = document.createElement("div");
        actionGroup.className = "copilot-actions";
        actions.forEach((action) => {
            if (!action || typeof action.label !== "string") return;
            if (action.type === "navigate" && !pageDetails[action.page]) return;
            if (action.type === "highlight_zone" &&
                !/^[A-Z0-9_-]{1,12}$/i.test(action.zone || "")) return;
            if (action.type === "highlight_slot" &&
                !/^[A-Z0-9_-]{1,16}$/i.test(action.slot_id || "")) return;
            if (!["navigate", "highlight_zone", "highlight_slot"].includes(action.type)) return;

            const button = document.createElement("button");
            button.type = "button";
            button.className = "copilot-action";
            button.textContent = action.label;
            button.addEventListener("click", () => activateCopilotAction(action));
            actionGroup.append(button);
        });
        if (actionGroup.childElementCount) article.append(actionGroup);
    }

    const time = document.createElement("time");
    time.className = "copilot-time";
    time.dateTime = new Date().toISOString();
    time.textContent = formatChatTime();
    article.append(time);
    container.append(article);

    while (container.children.length > 80) {
        container.firstElementChild.remove();
    }
    scrollCopilotToLatest();
}

async function activateCopilotAction(action) {
    const page = action.type === "navigate" ? action.page : "parking";
    if (!pageDetails[page]) return;
    if (location.hash !== `#${page}`) {
        history.pushState(null, "", `#${page}`);
    }
    showPage(page);

    if (action.type === "highlight_zone" || action.type === "highlight_slot") {
        await loadParkingSlots();
        const map = $("liveMapContainer");
        if (!map) return;
        map.querySelectorAll(".copilot-highlighted").forEach((item) =>
            item.classList.remove("copilot-highlighted")
        );
        const target = action.type === "highlight_zone"
            ? map.querySelector(`.lm-zone-panel[data-zone="${CSS.escape(action.zone)}"]`)
            : map.querySelector(`.lm-zone-panel[data-zone="${CSS.escape(action.zone || "")}"]`);
        const slotTarget = action.type === "highlight_slot"
            ? map.querySelector(`.lm-slot-btn[data-slot-id="${CSS.escape(action.slot_id)}"]`)
            : null;
        const zoneTarget = target || slotTarget?.closest(".lm-zone-panel");
        zoneTarget?.classList.add("copilot-highlighted");
        slotTarget?.classList.add("copilot-highlighted");
        (slotTarget || zoneTarget)?.scrollIntoView({ behavior: "smooth", block: "center" });
        window.setTimeout(() => {
            zoneTarget?.classList.remove("copilot-highlighted");
            slotTarget?.classList.remove("copilot-highlighted");
        }, 4000);
    }
}

